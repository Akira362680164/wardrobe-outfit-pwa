import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  CATEGORY_LABELS,
  COLOR_CATALOG,
  COLOR_SWATCHES,
  GARMENT_CATEGORY_CATALOG,
  LEGACY_CATEGORY_MAP,
  GARMENT_STATUS_LABELS,
  SEASON_CATALOG,
  SEASON_LABELS,
  STYLE_CATALOG,
  STYLE_LABELS,
  WISHLIST_STATUS_LABELS,
} from "../packages/domain-catalog/dist/index.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = resolve(root, "apps/wechat-miniprogram/generated/catalogs.ts");
const checkOnly = process.argv.includes("--check");

const subcategoryLabels = Object.fromEntries(
  GARMENT_CATEGORY_CATALOG.flatMap((group) => group.subcategories.map((subcategory) => [subcategory.id, subcategory.label])),
);

const content = `// Generated by scripts/generate-miniprogram-catalogs.mjs. Do not edit manually.\n\n${[
  constant("MINI_COLOR_CATALOG", COLOR_CATALOG),
  record("MINI_COLOR_SWATCHES", COLOR_SWATCHES, "{ bg: string; border?: string }"),
  constant("MINI_CATEGORY_CATALOG", GARMENT_CATEGORY_CATALOG),
  record("MINI_LEGACY_CATEGORY_MAP", LEGACY_CATEGORY_MAP, "string"),
  record("MINI_CATEGORY_LABELS", CATEGORY_LABELS, "string"),
  record("MINI_SUBCATEGORY_LABELS", subcategoryLabels, "string"),
  constant("MINI_SEASON_CATALOG", SEASON_CATALOG),
  record("MINI_SEASON_LABELS", SEASON_LABELS, "string"),
  constant("MINI_STYLE_CATALOG", STYLE_CATALOG),
  record("MINI_STYLE_LABELS", STYLE_LABELS, "string"),
  record("MINI_GARMENT_STATUS_LABELS", GARMENT_STATUS_LABELS, "string"),
  record("MINI_WISHLIST_STATUS_LABELS", WISHLIST_STATUS_LABELS, "string"),
].join("\n\n")}\n`;

if (checkOnly) {
  let current = "";
  try {
    current = await readFile(target, "utf8");
  } catch {
    // Missing output is handled by the same stale-file message.
  }
  if (current !== content) {
    console.error("apps/wechat-miniprogram/generated/catalogs.ts is out of date. Run npm run catalog:miniprogram:generate.");
    process.exitCode = 1;
  } else {
    console.log("miniprogram catalogs are up to date");
  }
} else {
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, content, "utf8");
  console.log("generated apps/wechat-miniprogram/generated/catalogs.ts");
}

function constant(name, value) {
  return `export const ${name} = ${JSON.stringify(value, null, 2)} as const;`;
}

function record(name, value, valueType) {
  return `export const ${name}: Readonly<Record<string, ${valueType}>> = ${JSON.stringify(value, null, 2)};`;
}
