import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as Lucide from "lucide-react";

const checkOnly = process.argv.includes("--check");
const repoRoot = process.cwd();
const assetDir = path.join(repoRoot, "apps/wechat-miniprogram/assets/icons");
const manifestPath = path.join(repoRoot, "apps/wechat-miniprogram/components/ui/icon/generated-icons.ts");

const icons = {
  home: "House",
  wardrobe: "Shirt",
  camera: "Camera",
  "camera-plus": "ImagePlus",
  image: "Image",
  scissors: "Scissors",
  trash: "Trash2",
  "rotate-left": "RotateCcw",
  "rotate-right": "RotateCw",
  reset: "RefreshCcw",
  layers: "Layers3",
  sparkles: "Sparkles",
  "shopping-bag": "ShoppingBag",
  user: "UserRound",
  settings: "Settings",
  "chevron-right": "ChevronRight",
  "chevron-left": "ChevronLeft",
  "chevron-down": "ChevronDown",
  search: "Search",
  "bar-chart-3": "ChartNoAxesColumn",
  "wand-sparkles": "WandSparkles",
  plus: "Plus",
  x: "X",
  check: "Check",
  loader: "LoaderCircle",
};

const tones = {
  ink: "#1d2228",
  surface: "#fffffc",
  primary: "#355c7d",
  danger: "#dc2626",
};

const outputs = new Map();
for (const [name, componentName] of Object.entries(icons)) {
  const Icon = Lucide[componentName];
  if (!Icon) throw new Error(`Missing Lucide icon export: ${componentName}`);
  for (const [tone, color] of Object.entries(tones)) {
    const filename = tone === "ink" ? `${name}.svg` : `${name}-${tone}.svg`;
    const markup = renderToStaticMarkup(React.createElement(Icon, {
      xmlns: "http://www.w3.org/2000/svg",
      width: 24,
      height: 24,
      color,
      strokeWidth: 2,
      "aria-hidden": "true",
    }));
    outputs.set(path.join(assetDir, filename), `${markup}\n`);
  }
}

const manifestLines = [
  "// Generated by scripts/generate-miniprogram-icons.mjs. Do not edit manually.",
  `export const ICON_TONES = ${JSON.stringify(Object.keys(tones))} as const;`,
  "export type UiIconTone = typeof ICON_TONES[number];",
  "export const ICON_PATHS = {",
];
for (const name of Object.keys(icons)) {
  manifestLines.push(`  ${JSON.stringify(name)}: {`);
  for (const tone of Object.keys(tones)) {
    const filename = tone === "ink" ? `${name}.svg` : `${name}-${tone}.svg`;
    manifestLines.push(`    ${tone}: ${JSON.stringify(`/assets/icons/${filename}`)},`);
  }
  manifestLines.push("  },");
}
manifestLines.push("} as const;", "export type UiIconName = keyof typeof ICON_PATHS;", "");
outputs.set(manifestPath, manifestLines.join("\n"));

const stale = [];
for (const [file, content] of outputs) {
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === content) continue;
  stale.push(path.relative(repoRoot, file));
  if (!checkOnly) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
}

if (checkOnly && stale.length) {
  console.error(`Mini-program icons are stale:\n${stale.join("\n")}`);
  process.exitCode = 1;
} else {
  console.log(checkOnly ? "Mini-program icons are up to date." : `Generated ${outputs.size} mini-program icon files.`);
}
